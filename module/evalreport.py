"""Markdown summary of the full-scan evaluation on simulated events.

  ./run.py evalreport [--candidates DIR] [-o output/efficiency_report.md]

Compares the physical focal steps (dz 3.0 / 1.5 um datasets) for method
A with the three depth conventions, the XY accuracy and the z_best bias,
and method B' against method A, all with chance levels from shifted
truths. Every number is recomputed from the candidate files.
"""

import argparse
from pathlib import Path

import numpy as np

from . import config
from . import efficiency as eff
from .report import DEFAULT_CANDIDATES

TOLS = [6., 12.]
METRICS = ("edge", "inclusive", "best")
VERTICES = (("capture", "capture"), ("LL decay", "HypernucleusDecay"))
SHIFTS = eff.random_shifts(eff.DEFAULT_N_SHIFTS, eff.DEFAULT_SHIFT_MIN_PX,
                           eff.DEFAULT_SHIFT_MAX_PX, np.random.default_rng(0))
STACK_THIRDS = ("first", "middle", "last")


def _sel(rows, vtype, control):
  rs = eff._select(rows, vtype, control)
  if vtype == "HypernucleusDecay":
    rs = [r for r in rs if r["parent"].startswith(eff.LL_PREFIX)]
  return rs


def efficiency_rows(dataset, csv_path, min_score=None, only_events=None):
  events = eff.load_truth(config.IMAGE_DIR / dataset)
  if only_events is not None:
    events = {k: v for k, v in events.items() if k in only_events}
  cands = eff.load_candidates(csv_path, min_score)
  if "bprime" in Path(csv_path).name:
    # B' runs may cover only the first events of a dataset: evaluate the
    # events present in the file (all of them have thousands of points)
    present = set(eff.load_candidates(csv_path))
    events = {k: v for k, v in events.items() if k in present}
  rows, extra = eff.evaluate(events, cands, TOLS, SHIFTS, "developed")
  return events, cands, rows, extra


def cell(rows, vtype, metric, tol):
  if vtype == "LL event":
    sel = eff._ll_events(rows, False, TOLS)
    ctrl = eff._ll_events(rows, True, TOLS)
  else:
    sel, ctrl = _sel(rows, vtype, False), _sel(rows, vtype, True)
  k = f"found_{metric}_{tol:g}"
  if not sel or k not in sel[0]:
    return "-"
  return (f"{np.mean([r[k] for r in sel]):.0%} "
          f"({np.mean([r[k] for r in ctrl]):.0%})")


def nearest_line(label, near, vtype):
  t = np.array(near["true"].get(vtype, []))
  c = np.array(near["control"].get(vtype, []))
  if len(t) == 0:
    return f"| {label} | - | - | - | - |"
  return (f"| {label} | {np.median(t[:, 0]):.1f} ({np.median(c[:, 0]):.1f}) "
          f"| {np.mean(t[:, 0] < 6):.0%} ({np.mean(c[:, 0] < 6):.0%}) "
          f"| {np.median(t[:, 1]):.1f} ({np.median(c[:, 1]):.1f}) "
          f"| {np.nanmedian(t[:, 2]):.1f} ({np.nanmedian(c[:, 2]):.1f}) |")


def zbias_by_stack(events, cands, vtype, max_xy=12.):
  """Median z_best - z_true (um) per third of the stack and overall."""
  per = {k: [] for k in range(3)}
  for name, truth in events.items():
    cs = [c for c in cands.get(name, []) if "z_best" in c]
    if not cs:
      continue
    cc = np.array([[c["col"], c["row"]] for c in cs])
    for v in truth["vertices"]:
      if v["type"] != vtype or not v["in_view"]:
        continue
      dxy = np.hypot(cc[:, 0] - v["col"], cc[:, 1] - v["row"]) \
        * truth["pixel_um"]
      j = int(np.argmin(dxy))
      if dxy[j] > max_xy:
        continue
      sl = (cs[j]["z_best"] - truth["stage_z0_mm"]) / truth["stage_dz_mm"]
      third = min(int(3 * v["slice"] / truth["n_slices"]), 2)
      per[third].append((sl - v["slice"]) * truth["physical_dz_um"])
  allv = sum(per.values(), [])
  med = lambda v: f"{np.median(v):+.1f}" if v else "-"
  spread = (f"{np.percentile(allv, 16):+.0f}/{np.percentile(allv, 84):+.0f}"
            if allv else "-")
  return [med(allv), spread] + [med(per[k]) for k in range(3)], len(allv)


def main():
  parser = argparse.ArgumentParser(
    description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
  parser.add_argument("--candidates", default=str(DEFAULT_CANDIDATES))
  parser.add_argument("-o", "--output",
                      default=str(config.OUTPUT_DIR / "efficiency_report.md"))
  args = parser.parse_args()
  cdir = Path(args.candidates)

  out = ["# Full-scan vertex finding on simulated E07 events", "",
         "Generated by `./run.py evalreport` (e07-g4-hypernuclei). "
         "Signal: Geant4 Xi- + 12C -> LL6He + 4He + t with weak decays, "
         "rendered with the calibrated image model v3 and embedded into "
         "random real tohoku-v1 views (background, fog, beam and noise are "
         "real). Candidates: e07-fullscan method A (merge_vertex_slices, "
         "production and relaxed cuts) and B' (branch points).", "",
         "Matching: one-to-one, 3-D distance in the developed emulsion. "
         "Depth conventions for method A candidates: **edge** = distance "
         "to the nearer end of the candidate z range, **inclusive** = zero "
         "inside the range, **best** = z_best (slice where most tracks "
         "cross) as a point. Each cell: efficiency (chance level from 10 "
         "random shifts of the truths by 400-1000 px).", ""]

  # 1. dz comparison for method A
  out += ["## 1. Physical focal step: dz 3.0 vs 1.5 um (method A, "
          "100 events each)", ""]
  head = " | ".join(f"{m} <{t:g} um" for m in METRICS for t in TOLS)
  for cuts in ("production", "relaxed"):
    out += [f"### {cuts} cuts", "",
            f"| dz | vertex | {head} | cand/event |",
            "|" + "---|" * (3 + len(METRICS) * len(TOLS))]
    for dz in ("3.0", "1.5"):
      ds = f"v3_embed_nagara_dz{dz}"
      path = cdir / f"{ds}_methodA_{cuts}.csv"
      if not path.exists():
        continue
      events, cands, rows, extra = efficiency_rows(ds, path)
      per_event = extra["n_candidates"] / len(events)
      for label, vtype in VERTICES + (("LL event", "LL event"),):
        out.append(f"| {dz} | {label} | " + " | ".join(
          cell(rows, vtype, m, t) for m in METRICS for t in TOLS)
          + f" | {per_event:.0f} |")
    out.append("")

  # 1b. background control: method A on the real views before embedding
  bg_lines = []
  for cuts in ("production", "relaxed"):
    bg_path = cdir / f"v3_bgonly_nagara_methodA_{cuts}.csv"
    if not bg_path.exists():
      continue
    bg = eff.load_candidates(bg_path)
    for dz in ("3.0", "1.5"):
      ds = f"v3_embed_nagara_dz{dz}"
      path = cdir / f"{ds}_methodA_{cuts}.csv"
      if not path.exists():
        continue
      events = eff.load_truth(config.IMAGE_DIR / ds)
      rows, _ = eff.evaluate(events, eff.load_candidates(path), TOLS,
                             SHIFTS, "developed", bg)
      for label, vtype in VERTICES:
        sel = _sel(rows, vtype, False)
        bsel = _sel(rows, vtype, "background")
        cells = []
        for m in METRICS:
          for t in TOLS:
            k = f"found_{m}_{t:g}"
            cells.append(f"{np.mean([r[k] for r in sel]):.0%} "
                         f"[{np.mean([r[k] for r in bsel]):.0%}]")
        bg_lines.append(f"| {cuts} | {dz} | {label} | "
                        + " | ".join(cells) + " |")
  if bg_lines:
    out += ["### Background control (same real views before embedding)", "",
            "Method A run on the original real views (no signal) and "
            "matched to the same true positions: efficiency [background "
            "rate]. It agrees with the shifted-truth chance level above.",
            "", f"| cuts | dz | vertex | {head} |",
            "|" + "---|" * (3 + len(METRICS) * len(TOLS))] + bg_lines + [""]

  # 2. XY accuracy and depth
  out += ["## 2. Nearest candidate in XY (method A production)", "",
          "Median XY distance, fraction within 6 um in XY, median depth "
          "gap of that candidate to its z-range edge and to z_best (um); "
          "control in parentheses.", "",
          "| dataset / vertex | XY median | XY <6 um | z gap edge | "
          "z gap z_best |", "|---|---|---|---|---|"]
  zb_rows = []
  for dz in ("3.0", "1.5"):
    ds = f"v3_embed_nagara_dz{dz}"
    path = cdir / f"{ds}_methodA_production.csv"
    if not path.exists():
      continue
    events = eff.load_truth(config.IMAGE_DIR / ds)
    cands = eff.load_candidates(path)
    near = eff.nearest_components(events, cands, SHIFTS, "developed")
    for label, vtype in VERTICES:
      out.append(nearest_line(f"dz {dz} {label}", near, vtype))
      vals, n = zbias_by_stack(events, cands, vtype)
      zb_rows.append(f"| dz {dz} {label} | {n} | " + " | ".join(vals)
                     + " |")
  out += ["", "## 3. Depth bias of z_best (method A production)", "",
          "z_best - z_true (developed um; + = larger slice index = smaller "
          "tohoku stage z) for the XY-nearest candidate within 12 um, "
          "overall and by the position of the vertex in the image stack.",
          "", "| dataset / vertex | n | median | p16/p84 | first third | "
          "middle third | last third |", "|---|---|---|---|---|---|---|"]
  out += zb_rows + [""]

  # 3. B' vs method A
  out += ["## 4. Method B' vs method A (5 events per dz)", "",
          "B' candidates are points (all depth conventions coincide); "
          "multiplicity cuts on the branch-point multiplicity. Method A "
          "uses the inclusive convention (these files have no z_best).",
          "", "| dz | method | vertex | <6 um | <12 um | cand/event |",
          "|---|---|---|---|---|---|"]
  for dz in ("3.0", "1.5"):
    ds = f"v3_embed_nagara5_dz{dz}"
    pairs = [("A production", f"{ds}_methodA_production.csv", None,
              "inclusive"),
             ("B' all", f"{ds}_bprime.csv", None, "edge"),
             ("B' mult >= 3", f"{ds}_bprime.csv", 3, "edge"),
             ("B' mult >= 4", f"{ds}_bprime.csv", 4, "edge")]
    for label, name, min_score, metric in pairs:
      path = cdir / name
      # B' files are appended per event: use them only once complete
      if not path.exists() or ("bprime" in name
                               and not path.with_suffix(".done").exists()):
        continue
      events, cands, rows, extra = efficiency_rows(ds, path, min_score)
      per_event = extra["n_candidates"] / len(events)
      for vlabel, vtype in VERTICES:
        out.append(f"| {dz} | {label} | {vlabel} | "
                   + " | ".join(cell(rows, vtype, metric, t) for t in TOLS)
                   + f" | {per_event:.0f} |")
  out.append("")

  # 4b. B' vs A on the same 20 events of the 100-event dataset
  ds = "v3_embed_nagara_dz3.0"
  bp = cdir / f"{ds}_bprime.csv"
  if bp.exists() and bp.with_suffix(".done").exists():
    present = set(eff.load_candidates(bp))
    out += [f"### B' vs A on the same {len(present)} events "
            f"({ds})", "",
            "| method | vertex | <6 um | <12 um | cand/event |",
            "|---|---|---|---|---|"]
    rows_spec = [("A production (best)", f"{ds}_methodA_production.csv",
                  None, "best"),
                 ("A production (inclusive)",
                  f"{ds}_methodA_production.csv", None, "inclusive"),
                 ("B' all", f"{ds}_bprime.csv", None, "edge"),
                 ("B' mult >= 3", f"{ds}_bprime.csv", 3, "edge"),
                 ("B' mult >= 4", f"{ds}_bprime.csv", 4, "edge"),
                 ("B' mult >= 5", f"{ds}_bprime.csv", 5, "edge")]
    for label, name, min_score, metric in rows_spec:
      events, cands, rows, extra = efficiency_rows(ds, cdir / name,
                                                   min_score, present)
      per_event = extra["n_candidates"] / len(events)
      for vlabel, vtype in VERTICES + (("LL event", "LL event"),):
        out.append(f"| {label} | {vlabel} | "
                   + " | ".join(cell(rows, vtype, metric, t) for t in TOLS)
                   + f" | {per_event:.0f} |")
    out.append("")

  # 4c. ranking of B' candidates by image darkness (precomputed studies)
  study = config.OUTPUT_DIR / "bprime_ranking.md"
  if study.exists():
    out += [study.read_text(), ""]
  specials = config.OUTPUT_DIR / "specials_ranking.md"
  if specials.exists():
    out += ["### Ranking of B' branch points on the real special events "
            "(`./run.py specialsrank`)", "",
            "Match: 200 px in XY and 30 um in stage z of the clicked "
            "vertex. On real events the multiplicity ranks well for most "
            "events (unlike the simulation, where the simulated vertices "
            "rarely produce high-multiplicity branch points), the "
            "darkness for others, and their combination ranks the true "
            "vertex better than the shifted control in all nine events.",
            "", specials.read_text(), ""]

  # 5. other channels with method A
  others = [("v3_embed_ll11be_dz3.0", "Xi- + 14N -> LL11Be + 4He"),
            ("v3_embed_ibuki_dz3.0", "Xi- + 14N -> L10Be + L5He (twin)"),
            ("v3_embed_nagara_replay_dz3.0", "Nagara replay"),
            ("v3_embed_ibuki_replay_dz3.0", "Ibuki replay"),
            ("v3_synth_nagara_replay_dz3.0", "Nagara replay, synthetic"),
            ("v3_synth_ibuki_replay_dz3.0", "Ibuki replay, synthetic"),
            ("v4_synth_nagara5_dz3.0", "Nagara, synthetic v4"),
            ("v4_synth_nagara_replay_dz3.0", "Nagara replay, synthetic v4"),
            ("v4_synth_ibuki_replay_dz3.0", "Ibuki replay, synthetic v4"),
            ("v11_synth_nagara10_dz3.0", "Nagara, synthetic v11"),
            ("v11_synth_nagara_replay_dz3.0", "Nagara replay, synthetic v11"),
            ("v11_synth_ibuki_replay_dz3.0", "Ibuki replay, synthetic v11"),
            ("v14_synth_nagara_replay_dz1.5",
             "Nagara replay, synthetic v14 (dz 1.5)"),
            ("v14_synth_ibuki_replay_dz1.5",
             "Ibuki replay, synthetic v14 (dz 1.5)")]
  lines = []
  sources = []
  for ds, label in others:
    sources.append((ds, label, f"{ds}_methodA_production.csv", None,
                    ("inclusive", "best")))
    sources.append((ds, label + " [B' mult >= 3]", f"{ds}_bprime.csv", 3,
                    ("edge", "edge")))
  for ds, label, name, min_score, metrics in sources:
    path = cdir / name
    if not (config.IMAGE_DIR / ds).exists():
      continue  # dataset removed (superseded image model)
    if not path.exists() or ("bprime" in name
                             and not path.with_suffix(".done").exists()):
      continue
    events, cands, rows, extra = efficiency_rows(ds, path, min_score)
    per_event = extra["n_candidates"] / len(events)
    for vlabel, vtype in (("capture", "capture"),
                          ("hypernuclear decays", "HypernucleusDecay")):
      sel = eff._select(rows, vtype, False)
      ctrl = eff._select(rows, vtype, True)
      if not sel:
        continue
      cells = []
      for m in metrics:
        for t in TOLS:
          k = f"found_{m}_{t:g}"
          cells.append(f"{np.mean([r[k] for r in sel]):.0%} "
                       f"({np.mean([r[k] for r in ctrl]):.0%})"
                       if k in sel[0] else "-")
      lines.append(f"| {label} | {vlabel} | {len(sel)} | "
                   + " | ".join(cells) + f" | {per_event:.0f} |")
  if lines:
    out += ["", "## 5. Other channels (dz 3.0 unless noted)", "",
            "Method A production with the inclusive and z_best "
            "conventions; B' rows (point candidates, multiplicity >= 3) "
            "repeat the point distance in both column pairs. The B' replay "
            "runs cover the first 10 events (ev0000-0009) of each replay "
            "dataset.", "",
            "| dataset | vertices | n | inclusive <6 um | inclusive <12 um "
            "| best <6 um | best <12 um | cand/event |",
            "|---|---|---|---|---|---|---|---|"] + lines

  out += ["", "## Reading the tables", "",
          "- The excess over the shifted-truth chance level is a measure "
          "of association, not an efficiency by itself; with ~800 method-A "
          "candidates per real view a 30 um tolerance is reached by chance "
          "in most cases, hence 6 and 12 um here. A stronger control is the "
          "method run on the same real views before embedding (section 1, "
          "background control; `./run.py efficiency "
          "--background-candidates`).",
          "- The dz comparison shows how method A performs if the "
          "physical focal step is 3.0 or 1.5 um per slice; it does not "
          "measure the step itself. Calibrating the image model under "
          "either step could not distinguish them "
          "(output/dz_comparison.md).",
          "- z_best is pulled towards the middle of the image stack for "
          "vertices near its ends (section 3); a correction or a "
          "normalization of the crossing counts near the stack ends would "
          "sharpen it.",
          "- Section 4 (5 events per dz) is indicative only; the 20-event "
          "comparison is the basis for B' vs A: B' (all branch points) has "
          "a larger excess over chance at 6 um than method A but ~40 times "
          "more candidates per view, and cuts on the branch multiplicity "
          "remove the signal faster than the background.",
          "- Synthetic v3 images give ~40 method-A candidates per view, "
          "synthetic v4 ~795, v11 ~905 and v14 ~875, close to the ~770 of "
          "real "
          "views: these backgrounds reproduce the candidate rate of real "
          "data, so their efficiencies can be compared with the embedded "
          "ones.",
          "- The physical step is discussed in output/dz_comparison.md: "
          "grains counted along perpendicular beam tracks favour ~1.5 um "
          "per slice, given the MIP grain density and Sh = 1.9."]
  out.append("")
  Path(args.output).write_text("\n".join(out) + "\n")
  print("\n".join(out))
  print(f"-> {args.output}")


if __name__ == "__main__":
  main()
